from __future__ import annotations

import pandas as pd

# --------------------------------------------------------------- 日期与 OHLC 辅助


def make_dates(n: int, start: str = "2024-01-02") -> list:
    """n 个合成交易日（工作日历，仅作 bar 日期载体，不与 trade_calendar 交互）。"""
    return [d.strftime("%Y-%m-%d") for d in pd.bdate_range(start, periods=n)]


def bars_to_ohlc(hl: list, dates: list = None) -> pd.DataFrame:
    """(high, low) 列表 → 合成 OHLC DataFrame（trade_date/open/high/low/close）。

    机械规则：bar 相对前一根 h、l 同增视为向上（首根按与后一根关系），向上
    open=low/close=high，向下 open=high/close=low。结构引擎只用 high/low；
    open/close 仅供 open_qfq 类用例与完整性。
    """
    if dates is None:
        dates = make_dates(len(hl))
    rows = []
    for i, (h, l) in enumerate(hl):
        if i + 1 < len(hl):
            up = hl[i + 1][0] > h  # 下一根更高 → 本根处于上行腿
        else:
            up = hl[i][0] > hl[i - 1][0] if i else True
        o, c = (l, h) if up else (h, l)
        rows.append({"trade_date": dates[i], "open": o, "high": h,
                     "low": l, "close": c})
    return pd.DataFrame(rows)


